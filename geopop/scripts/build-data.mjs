// Builds GeoPop's data from two open datasets (run: npm run data):
//   world-countries (mledoze/countries, ODbL): names, capitals, borders,
//     languages, money, regions -> src/data/countries.js
//   world-atlas (Natural Earth 1:50m, public domain): country shapes ->
//     public/world-50m.json
//   flag-icons (MIT): one SVG per flag -> public/flags/
import fs from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const wc = require('world-countries');
const topo = require('world-atlas/countries-50m.json');

// The countries GeoPop teaches: the 193 UN members, plus the Vatican,
// Palestine (UN observers), Taiwan and Kosovo.
const EXTRA = ['TW', 'XK', 'PS', 'VA'];
const list = wc.filter((c) => c.unMember || EXTRA.includes(c.cca2));
const by3 = Object.fromEntries(wc.map((c) => [c.cca3, c.cca2]));
const keep = new Set(list.map((c) => c.cca2));

// Kid-friendly names where the dataset's common name is formal or rare.
const NAME_FIX = {
  CD: 'DR Congo',
  CG: 'Republic of the Congo',
  CI: 'Ivory Coast',
  VA: 'Vatican City',
  FM: 'Micronesia',
  ST: 'São Tomé and Príncipe',
  MM: 'Myanmar',
};

const countries = list
  .map((c) => ({
    id: c.cca2,
    n3: c.ccn3,
    name: NAME_FIX[c.cca2] || c.name.common,
    capital: (c.capital || [])[0] || null,
    lat: c.latlng[0],
    lng: c.latlng[1],
    region: c.region,
    sub: c.subregion || c.region,
    borders: (c.borders || []).map((b) => by3[b]).filter((b) => keep.has(b)),
    area: Math.round(c.area),
    langs: Object.values(c.languages || {}).slice(0, 3),
    money: Object.values(c.currencies || {}).map((m) => m.name).slice(0, 2),
    people: c.demonyms?.eng?.m || null,
    landlocked: !!c.landlocked,
  }))
  .sort((a, b) => a.name.localeCompare(b.name));

fs.writeFileSync(
  'src/data/countries.js',
  `// Generated by scripts/build-data.mjs from world-countries (ODbL). Don't edit by hand.\nexport const COUNTRIES = ${JSON.stringify(countries)};\n`,
);

// Shapes: give the few unnamed shapes their country (or none), and keep
// territories (Greenland, Western Sahara…) as plain land with no country.
const byN3 = Object.fromEntries(countries.map((c) => [c.n3, c.id]));
const BY_NAME = { Kosovo: 'XK', Somaliland: 'SO', 'N. Cyprus': 'CY' };
for (const g of topo.objects.countries.geometries) {
  const id = BY_NAME[g.properties.name] || byN3[g.id] || null;
  g.properties = { id, name: g.properties.name };
  delete g.id;
}
fs.writeFileSync('public/world-50m.json', JSON.stringify(topo));

for (const c of countries) {
  fs.copyFileSync(`node_modules/flag-icons/flags/4x3/${c.id.toLowerCase()}.svg`, `public/flags/${c.id.toLowerCase()}.svg`);
}
console.log(`${countries.length} countries, ${topo.objects.countries.geometries.length} shapes, flags copied.`);
